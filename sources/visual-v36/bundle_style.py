"""Bundle RoomRestyle_pass*.luau into RoomStyle.server.luau (appended to the server script by build_place.py)."""
from pathlib import Path
folder = Path(__file__).resolve().parent
parts = ["RoomRestyle_pass1.luau", "RoomRestyle_pass2.luau", "RoomRestyle_pass3.luau", "RoomRestyle_pass5_furniture.luau"]
out = ["-- KONTUR v36 room restyle: palette, materials, cove lights, rugs, plants. Generated by bundle_style.py.\n",
       "do\nlocal officeForStyle=workspace:WaitForChild(\"OfficeMap\",30)\nif officeForStyle then\n"]
for f in parts:
    out.append(f"local ok,err=pcall(function()\n{(folder / f).read_text()}\nend)\nif not ok then warn('KonturV36 {f}: '..tostring(err)) end\n")
out.append("end\nend\n")
(folder / "RoomStyle.server.luau").write_text("".join(out))
